from __future__ import annotations
from backend.tools.mapping.models import RelationalSchema, Table


def generate_ddl(schema: RelationalSchema, dialect: str = "postgres") -> str:
    """Generate PostgreSQL-compliant DDL scripts from a RelationalSchema.
    Includes:
      - Topological sorting of tables to satisfy foreign key dependencies
      - Primary Key and Foreign Key constraints with ON DELETE CASCADE
      - NOT NULL and UNIQUE specifications
      - Performance B-Tree indexes on all foreign key columns
    """
    lines: list[str] = [
        "-- ====================================================",
        "-- Generated by Normie DDL generator",
        f"-- Dialect: {dialect.upper()}",
        "-- ====================================================\n",
    ]

    # Topological sort of tables based on foreign keys
    tables_by_name = {t.name: t for t in schema.tables}
    visited: set[str] = set()
    visiting: set[str] = set()
    sorted_tables: list[Table] = []

    def visit(name: str):
        if name in visiting:
            # cycle detected, will break later
            return
        if name not in visited and name in tables_by_name:
            visiting.add(name)
            table = tables_by_name[name]
            for fk in table.foreign_keys:
                if fk.ref_table != name:
                    visit(fk.ref_table)
            visiting.remove(name)
            visited.add(name)
            sorted_tables.append(table)

    for t_name in tables_by_name:
        if t_name not in visited:
            visit(t_name)

    indexes: list[str] = []

    for table in sorted_tables:
        lines.append(f"CREATE TABLE IF NOT EXISTS {table.name} (")
        col_defs: list[str] = []

        for col in table.columns:
            parts = [f"    {col.name}", col.type]
            if not col.is_nullable:
                parts.append("NOT NULL")
            if col.is_unique and not col.is_pk:
                parts.append("UNIQUE")
            col_defs.append(" ".join(parts))

        # Primary Key constraint
        if table.primary_key:
            pk_cols = ", ".join(table.primary_key)
            col_defs.append(f"    CONSTRAINT pk_{table.name} PRIMARY KEY ({pk_cols})")

        # Foreign Key constraints
        for idx, fk in enumerate(table.foreign_keys):
            fk_cols = ", ".join(fk.columns)
            ref_cols = ", ".join(fk.ref_columns)
            constraint_name = f"fk_{table.name}_{fk.ref_table}_{idx + 1}"
            col_defs.append(
                f"    CONSTRAINT {constraint_name} FOREIGN KEY ({fk_cols}) "
                f"REFERENCES {fk.ref_table} ({ref_cols}) ON DELETE {fk.on_delete}"
            )

            # Record index creation on FK columns
            idx_name = f"idx_{table.name}_{'_'.join(fk.columns)}"
            indexes.append(f"CREATE INDEX IF NOT EXISTS {idx_name} ON {table.name} ({fk_cols});")

        lines.append(",\n".join(col_defs))
        lines.append(");\n")

    # Append index statements
    if indexes:
        lines.append("-- Foreign Key Indexing")
        lines.extend(indexes)
        lines.append("")

    return "\n".join(lines)
